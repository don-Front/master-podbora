class FaqExcelFormulationsTests(SimpleTestCase):
    def test_each_excel_question_has_five_recognized_formulations(self):
        self.assertEqual(len(FAQ_FORMULATIONS), 18)
        for expected_question, formulations in FAQ_FORMULATIONS.items():
            self.assertEqual(len(formulations), 5, expected_question)
            for phrase in formulations:
                with self.subTest(expected_question=expected_question, phrase=phrase):
                    result = faq_service.answer(phrase)
                    self.assertTrue(result.handled, phrase)
                    self.assertIsNotNone(result.match, phrase)
                    if result.hints:
                        self.assertEqual(result.hints[1], expected_question)
                    else:
                        self.assertEqual(result.match.entry.question, expected_question)

    def test_repair_formulations_attach_pdf(self):
        for phrase in FAQ_FORMULATIONS[
            "Как отправить оборудование для платного или гарантийного ремонта"
        ]:
            with self.subTest(phrase=phrase):
                result = faq_service.answer(phrase)
                if result.hints:
                    result = faq_service.answer(result.hints[1], from_hint=True)
                self.assertTrue(result.handled)
                self.assertIsNotNone(result.attachment_path)
                self.assertTrue(result.attachment_path.is_file())

    def test_rag_questions_are_not_taken_by_faq(self):
        for phrase in RAG_SAFE_QUESTIONS:
            with self.subTest(phrase=phrase):
                result = faq_service.answer(phrase)
                self.assertFalse(result.handled)
                self.assertTrue(result.needs_rag)
