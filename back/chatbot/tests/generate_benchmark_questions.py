def main() -> None:
    pdfs = [
        os.path.basename(p)
        for p in glob.glob(os.path.join(_DOCS, "**", "*.pdf"), recursive=True)
    ]
    all_q: list[dict] = []
    for name in sorted(pdfs):
        gen = GENERATORS.get(name)
        if gen:
            qs = gen()
        elif name.startswith("ОТ ") or name.startswith("2024-"):
            product = "Turbo Flow UFG"
            if "UFL" in name:
                product = "Turbo Flow UFL"
            elif "CFM" in name:
                product = "Turbo Flow CFM"
            elif "GFG" in name:
                product = "GFG"
            elif "TFG" in name:
                product = "Turbo Flow TFG"
            elif "UDM" in name:
                product = "UDM"
            ot_num = name.split(" от ")[0].replace("ОТ ", "")
            qs = _ot_questions(name, product, ot_num)
        else:
            qs = [
                _q(name, i, f"Тема {i}", f"Что указано в документе {name} по теме {i}?", ["документ"])
                for i in range(1, 21)
            ]
        assert len(qs) == 20, f"{name}: {len(qs)} questions"
        all_q.extend(qs)

    payload = {
        "version": 1,
        "total_files": len(pdfs),
        "total_questions": len(all_q),
        "questions": all_q,
    }
    with open(_OUT, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
    print(f"Written {len(all_q)} questions for {len(pdfs)} files -> {_OUT}")


if __name__ == "__main__":
    main()
